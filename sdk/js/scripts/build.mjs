import { build } from 'esbuild';

const banner = {
  js: '/* @orbit360/javascript web client — generated by npm run build; source: sdk/js/src/client.mjs */',
};

const common = {
  entryPoints: ['src/client.mjs'],
  bundle: true,
  target: 'es2015',
  banner,
  logLevel: 'info',
};

await Promise.all([
  build({ ...common, format: 'iife', globalName: 'Orbit360', outfile: 'dist/orbit360-client.js' }),
  build({ ...common, format: 'esm', outfile: 'dist/orbit360-client.mjs' }),
  build({ ...common, format: 'cjs', outfile: 'dist/orbit360-client.cjs' }),
]);
